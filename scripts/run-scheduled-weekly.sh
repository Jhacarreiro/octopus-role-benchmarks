#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

LOCK_FILE="${BENCHMARK_LOCK_FILE:-/tmp/octopus-role-benchmarks-weekly.lock}"
exec 9>"$LOCK_FILE"
if ! flock -n 9; then
  echo "Benchmark refresh already running; exiting."
  exit 75
fi

if ! git diff --quiet || ! git diff --cached --quiet; then
  echo "Refusing benchmark refresh: working tree is not clean." >&2
  exit 2
fi

BRANCH="$(git branch --show-current)"
if [ "$BRANCH" != "main" ]; then
  echo "Refusing benchmark refresh: expected main branch, found ${BRANCH:-detached}." >&2
  exit 2
fi

git fetch origin main
git merge --ff-only origin/main

if [ "${BENCHMARK_SKIP_INSTALL:-0}" != "1" ]; then
  npm ci
fi

set +e
bash scripts/run-weekly-refresh.sh
refresh_code=$?
set -e

if [ "$refresh_code" -eq 0 ]; then
  npm run check:all
fi

# Always publish terminal public state when files changed, including an error
# refresh-status/weekly-review generated by run-weekly-refresh.sh.
git add data site/data methodology/cai-estimation-validation.md

if ! git diff --cached --quiet; then
  if [ "$refresh_code" -eq 0 ]; then
    msg="data: weekly benchmark snapshot $(date -u +%F)"
  else
    msg="status: benchmark refresh failed $(date -u +%F)"
  fi
  git commit -m "$msg"
  if [ "${BENCHMARK_NO_PUSH:-0}" != "1" ]; then
    git push origin main
  fi
else
  echo "No public benchmark state changes."
fi

if [ -f data/weekly-review.json ]; then
  jq -r '.message // empty' data/weekly-review.json
fi

exit "$refresh_code"
